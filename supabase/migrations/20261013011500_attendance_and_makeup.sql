-- Attendance (點名) and makeup lessons (補課).
-- Additive only: five new tables, no change to existing tables or data.
-- Every table is service-role only; the browser reaches them through the
-- attendance-manager Edge Function, which verifies the Firebase ID token and
-- re-checks role, teacher class permission and active enrollment.

-- 教材頁碼 → 影片時間對照表（管理員維護，老師選頁碼時自動帶入）
create table if not exists public.book_video_segments (
    id bigint generated by default as identity primary key,
    book_id bigint not null references public.books(id) on delete cascade,
    title text not null,
    page_from integer not null,
    page_to integer not null,
    video_url text not null,
    start_seconds integer not null default 0,
    end_seconds integer,
    is_active boolean not null default true,
    created_by bigint references public.students(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint book_video_segments_title_check check (char_length(btrim(title)) between 1 and 120),
    constraint book_video_segments_pages_check check (page_from between 1 and 999 and page_to between page_from and 999),
    constraint book_video_segments_url_check check (video_url ~* '^https://'),
    constraint book_video_segments_time_check check (
        start_seconds between 0 and 86400
        and (end_seconds is null or (end_seconds > start_seconds and end_seconds <= 86400))
    )
);
create index if not exists book_video_segments_book_pages_idx
    on public.book_video_segments (book_id, page_from, page_to)
    where is_active;
create index if not exists book_video_segments_created_by_idx
    on public.book_video_segments (created_by);

-- 一個班級一天一堂課
create table if not exists public.class_sessions (
    id bigint generated by default as identity primary key,
    class_id smallint not null references public.academy_classes(id) on delete restrict,
    session_date date not null,
    teacher_id bigint references public.students(id) on delete set null,
    note text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint class_sessions_unique unique (class_id, session_date),
    constraint class_sessions_note_check check (note is null or char_length(note) <= 500)
);
create index if not exists class_sessions_teacher_idx on public.class_sessions (teacher_id);

create table if not exists public.class_session_attendance (
    id bigint generated by default as identity primary key,
    session_id bigint not null references public.class_sessions(id) on delete cascade,
    student_id bigint not null references public.students(id) on delete cascade,
    status text not null,
    marked_by bigint references public.students(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint class_session_attendance_unique unique (session_id, student_id),
    constraint class_session_attendance_status_check check (status in ('present', 'late', 'absent', 'leave'))
);
create index if not exists class_session_attendance_student_idx
    on public.class_session_attendance (student_id, status);
create index if not exists class_session_attendance_marked_by_idx
    on public.class_session_attendance (marked_by);

-- 當天教學進度：影片時間段、聽力音檔、作業
create table if not exists public.class_session_progress_items (
    id bigint generated by default as identity primary key,
    session_id bigint not null references public.class_sessions(id) on delete cascade,
    item_type text not null,
    sort_order integer not null default 0,
    title text not null,
    book_id bigint references public.books(id) on delete set null,
    video_segment_id bigint references public.book_video_segments(id) on delete set null,
    video_url text,
    start_seconds integer,
    end_seconds integer,
    track_id bigint references public.music_tracks(id) on delete set null,
    assignment_id bigint references public.assignments(id) on delete set null,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint class_session_progress_items_type_check check (item_type in ('video', 'listening', 'assignment')),
    constraint class_session_progress_items_title_check check (char_length(btrim(title)) between 1 and 160),
    constraint class_session_progress_items_video_check check (
        item_type <> 'video'
        or (
            video_url ~* '^https://'
            and start_seconds between 0 and 86400
            and (end_seconds is null or (end_seconds > start_seconds and end_seconds <= 86400))
        )
    )
);
create index if not exists class_session_progress_items_session_idx
    on public.class_session_progress_items (session_id, sort_order);
create index if not exists class_session_progress_items_book_idx
    on public.class_session_progress_items (book_id);
create index if not exists class_session_progress_items_segment_idx
    on public.class_session_progress_items (video_segment_id);
create index if not exists class_session_progress_items_track_idx
    on public.class_session_progress_items (track_id);
create index if not exists class_session_progress_items_assignment_idx
    on public.class_session_progress_items (assignment_id);

-- 學生自行按「我看完了」的補課項目（影片）。聽力與作業改由既有紀錄判定。
create table if not exists public.makeup_item_completions (
    id bigint generated by default as identity primary key,
    progress_item_id bigint not null references public.class_session_progress_items(id) on delete cascade,
    student_id bigint not null references public.students(id) on delete cascade,
    completed_at timestamptz not null default now(),
    constraint makeup_item_completions_unique unique (progress_item_id, student_id)
);
create index if not exists makeup_item_completions_student_idx
    on public.makeup_item_completions (student_id);

