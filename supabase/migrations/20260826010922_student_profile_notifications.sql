-- Student-owned profile information is served only by Firebase-verified Edge Functions.
-- Date of birth is intentionally private: it is never exposed through leaderboard data.
alter table public.students
    add column if not exists date_of_birth date;

alter table public.students
    drop constraint if exists students_date_of_birth_reasonable;

alter table public.students
    add constraint students_date_of_birth_reasonable
    check (date_of_birth is null or date_of_birth >= date '1900-01-01');

create table if not exists public.student_notifications (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(id) on delete cascade,
    notification_type text not null default 'system'
        check (notification_type in ('system', 'assignment', 'reward', 'birthday', 'membership')),
    title text not null check (char_length(title) between 1 and 120),
    body text not null default '' check (char_length(body) <= 1000),
    metadata jsonb not null default '{}'::jsonb,
    read_at timestamptz,
    expires_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists idx_student_notifications_inbox
    on public.student_notifications(student_id, read_at, created_at desc);

alter table public.student_notifications enable row level security;
revoke all on public.student_notifications from anon, authenticated;
grant all on public.student_notifications to service_role;

