-- Keep the existing three-argument activation function working for already-open
-- browser tabs. The four-argument version records a new student's date of birth
-- within the same claim transaction.
create function public.claim_academy_account_invitation(
    p_token_hash text,
    p_firebase_uid text,
    p_login_email text,
    p_date_of_birth date
) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    v_result jsonb;
    v_student_id bigint;
begin
    if p_date_of_birth is not null and p_date_of_birth > current_date then
        raise exception using errcode = '22023', message = 'invalid_date_of_birth';
    end if;

    v_result := public.claim_academy_account_invitation(
        p_token_hash,
        p_firebase_uid,
        p_login_email
    );
    v_student_id := nullif(v_result ->> 'student_id', '')::bigint;

    if v_student_id is not null and p_date_of_birth is not null then
        update public.students
        set date_of_birth = p_date_of_birth,
            updated_at = now()
        where id = v_student_id
          and firebase_uid = btrim(coalesce(p_firebase_uid, ''));
    end if;

    return v_result;
end;
$$;

revoke all on function public.claim_academy_account_invitation(text, text, text, date)
    from public, anon, authenticated;
grant execute on function public.claim_academy_account_invitation(text, text, text, date)
    to service_role;
