-- Single-student academy class change (promote / demote) that keeps every class window.
-- Additive: one new enrollment status, one history table and one service-role-only function.
--
-- Why a new row instead of editing class_id: material retention, access grants and attendance
-- history are all computed from "which class, from which day to which day" windows, one window
-- per academy_enrollments row. Overwriting class_id (what apply_academy_placement_cycle does)
-- would pretend the student had always been in the new class.

-- 1) A closed window of a class change must not look like a departure ('withdrawn'/'graduated').
alter table public.academy_enrollments
    drop constraint if exists academy_enrollments_status_check;
alter table public.academy_enrollments
    add constraint academy_enrollments_status_check
    check (status in ('active', 'paused', 'withdrawn', 'graduated', 'transferred'));

comment on column public.academy_enrollments.status is
    'active, paused, withdrawn, graduated or transferred (window closed by a class change; the student is still enrolled in a newer row).';

-- 2) History of class changes.
create table if not exists public.academy_class_changes (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(id) on delete cascade,
    from_enrollment_id bigint not null references public.academy_enrollments(id) on delete restrict,
    to_enrollment_id bigint not null references public.academy_enrollments(id) on delete restrict,
    from_class_id smallint not null references public.academy_classes(id) on delete restrict,
    to_class_id smallint not null references public.academy_classes(id) on delete restrict,
    change_type text not null,
    effective_on date not null,
    reason text not null,
    changed_by bigint references public.students(id) on delete set null,
    created_at timestamptz not null default now(),
    constraint academy_class_changes_type_check check (change_type in ('promote', 'demote')),
    constraint academy_class_changes_class_differs_check check (from_class_id <> to_class_id),
    constraint academy_class_changes_reason_length_check check (char_length(reason) between 2 and 300)
);

comment on table public.academy_class_changes is
    'One row per single-student class change (promote or demote). Written only by change_academy_student_class().';

create index if not exists academy_class_changes_student_idx
    on public.academy_class_changes (student_id, effective_on desc, id desc);
create index if not exists academy_class_changes_from_enrollment_idx
    on public.academy_class_changes (from_enrollment_id);
create index if not exists academy_class_changes_to_enrollment_idx
    on public.academy_class_changes (to_enrollment_id);
create index if not exists academy_class_changes_from_class_idx
    on public.academy_class_changes (from_class_id);
create index if not exists academy_class_changes_to_class_idx
    on public.academy_class_changes (to_class_id);
create index if not exists academy_class_changes_changed_by_idx
    on public.academy_class_changes (changed_by)
    where changed_by is not null;

alter table public.academy_class_changes enable row level security;
revoke all on table public.academy_class_changes from anon, authenticated;

-- 3) The change itself. Called only by the academy-student-manager Edge Function, after it has
--    verified from the database that the caller is an admin.
create or replace function public.change_academy_student_class(
    p_student_id bigint,
    p_to_class_code text,
    p_effective_on date,
    p_reason text,
    p_changed_by bigint
)
returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
    today_taipei constant date := (now() at time zone 'Asia/Taipei')::date;
    current_row public.academy_enrollments%rowtype;
    from_class public.academy_classes%rowtype;
    to_class public.academy_classes%rowtype;
    clean_reason text := btrim(coalesce(p_reason, ''));
    new_enrollment_id bigint;
    direction text;
begin
    if p_student_id is null or p_effective_on is null then
        raise exception 'ACADEMY_CHANGE_INVALID_INPUT' using errcode = 'P0001';
    end if;
    if char_length(clean_reason) < 2 or char_length(clean_reason) > 300 then
        raise exception 'ACADEMY_CHANGE_REASON_INVALID' using errcode = 'P0001';
    end if;

    -- Lock the student's current window so two admins cannot change the same student at once.
    select *
    into current_row
    from public.academy_enrollments
    where student_id = p_student_id
      and status in ('active', 'paused')
    for update;

    if not found then
        raise exception 'ACADEMY_ENROLLMENT_NOT_FOUND' using errcode = 'P0001';
    end if;
    if current_row.status <> 'active' then
        raise exception 'ACADEMY_ENROLLMENT_NOT_ACTIVE' using errcode = 'P0001';
    end if;

    select * into from_class from public.academy_classes where id = current_row.class_id;
    select * into to_class
    from public.academy_classes
    where code = upper(btrim(coalesce(p_to_class_code, '')))
      and is_active;

    if not found then
        raise exception 'ACADEMY_CLASS_INVALID' using errcode = 'P0001';
    end if;
    if to_class.id = from_class.id then
        raise exception 'ACADEMY_CLASS_UNCHANGED' using errcode = 'P0001';
    end if;
    if p_effective_on > today_taipei then
        raise exception 'ACADEMY_CHANGE_DATE_IN_FUTURE' using errcode = 'P0001';
    end if;
    if p_effective_on < current_row.enrolled_at then
        raise exception 'ACADEMY_CHANGE_DATE_BEFORE_ENROLLMENT' using errcode = 'P0001';
    end if;
    if current_row.access_ends_at is not null and p_effective_on > current_row.access_ends_at then
        raise exception 'ACADEMY_CHANGE_DATE_AFTER_ACCESS_END' using errcode = 'P0001';
    end if;
    if current_row.scheduled_departure_at is not null and p_effective_on > current_row.scheduled_departure_at then
        raise exception 'ACADEMY_CHANGE_DATE_AFTER_DEPARTURE' using errcode = 'P0001';
    end if;

    direction := case when to_class.sort_order > from_class.sort_order then 'promote' else 'demote' end;

    if p_effective_on = current_row.enrolled_at then
        -- The student joined this class on the same day: there is no earlier window to close,
        -- so correcting the class on the existing row is exact.
        update public.academy_enrollments
        set class_id = to_class.id,
            status_changed_at = now(),
            notes = concat_ws(E'\n', nullif(notes, ''),
                concat('Class corrected from ', from_class.code, ' to ', to_class.code, ' on ', p_effective_on, '.')),
            updated_at = now()
        where id = current_row.id;
        new_enrollment_id := current_row.id;
    else
        -- Close the old window the day before, then open the new one. The old row is
        -- 'transferred' (not a departure), so material retention and access keep the old window.
        update public.academy_enrollments
        set status = 'transferred',
            access_ends_at = p_effective_on - 1,
            scheduled_departure_at = null,
            status_changed_at = now(),
            notes = concat_ws(E'\n', nullif(notes, ''),
                concat('Class changed from ', from_class.code, ' to ', to_class.code, ' on ', p_effective_on, '.')),
            updated_at = now()
        where id = current_row.id;

        insert into public.academy_enrollments (
            student_id, class_id, status, enrolled_at, access_ends_at, scheduled_departure_at, notes
        )
        values (
            current_row.student_id, to_class.id, 'active', p_effective_on,
            current_row.access_ends_at, current_row.scheduled_departure_at,
            concat('Class changed from ', from_class.code, ' on ', p_effective_on, '.')
        )
        returning id into new_enrollment_id;

        -- The access-grant trigger records any non-active status as "withdrawn"; this is a transfer.
        update public.student_access_grants
        set revoke_reason = 'Academy class changed.',
            updated_at = now()
        where source = 'academy_enrollment'
          and source_reference_type = 'academy_enrollment'
          and source_reference_id = current_row.id;
    end if;

    insert into public.academy_class_changes (
        student_id, from_enrollment_id, to_enrollment_id, from_class_id, to_class_id,
        change_type, effective_on, reason, changed_by
    )
    values (
        current_row.student_id, current_row.id, new_enrollment_id, from_class.id, to_class.id,
        direction, p_effective_on, clean_reason, p_changed_by
    );

    return jsonb_build_object(
        'student_id', current_row.student_id,
        'from_class', from_class.code,
        'to_class', to_class.code,
        'change_type', direction,
        'effective_on', p_effective_on,
        'enrollment_id', new_enrollment_id
    );
end;
$$;

revoke all on function public.change_academy_student_class(bigint, text, date, text, bigint)
    from public, anon, authenticated;
grant execute on function public.change_academy_student_class(bigint, text, date, text, bigint)
    to service_role;
