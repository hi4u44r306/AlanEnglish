-- Independent physical-material storefront.
-- Store accounts use Supabase Auth and intentionally do not link to Firebase students.

alter table public.material_packages
    add column if not exists inventory_quantity integer,
    add column if not exists max_quantity_per_order integer not null default 10;

alter table public.material_packages
    drop constraint if exists material_packages_inventory_nonnegative,
    add constraint material_packages_inventory_nonnegative
        check (inventory_quantity is null or inventory_quantity >= 0),
    drop constraint if exists material_packages_max_quantity_range,
    add constraint material_packages_max_quantity_range
        check (max_quantity_per_order between 1 and 20);

create table if not exists public.store_customer_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    email text not null,
    display_name text,
    phone text,
    stripe_customer_id text unique,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint store_customer_profiles_email_not_blank check (btrim(email) <> '')
);

create table if not exists public.store_shipping_methods (
    id bigint generated by default as identity primary key,
    code text not null unique,
    name text not null,
    fee_twd integer not null default 0 check (fee_twd >= 0),
    enabled boolean not null default true,
    sort_order integer not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

