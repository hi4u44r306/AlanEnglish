create or replace function private.ae_gamification_grant(
    p_student_id bigint,
    p_xp_delta integer,
    p_points_delta integer,
    p_source_type text,
    p_source_key text,
    p_description text default null,
    p_metadata jsonb default '{}'::jsonb
) returns boolean
language plpgsql
security invoker
set search_path = public, private, pg_temp
as $$
declare
    v_inserted integer := 0;
begin
    if p_student_id is null or coalesce(trim(p_source_type), '') = '' or coalesce(trim(p_source_key), '') = '' then
        return false;
    end if;
    if coalesce(p_xp_delta, 0) = 0 and coalesce(p_points_delta, 0) = 0 then
        return false;
    end if;

    insert into public.student_gamification_ledger (
        student_id, xp_delta, points_delta, source_type, source_key, description, metadata
    ) values (
        p_student_id,
        coalesce(p_xp_delta, 0),
        coalesce(p_points_delta, 0),
        trim(p_source_type),
        trim(p_source_key),
        nullif(trim(coalesce(p_description, '')), ''),
        coalesce(p_metadata, '{}'::jsonb)
    )
    on conflict (student_id, source_type, source_key) do nothing;

    get diagnostics v_inserted = row_count;
    if v_inserted = 0 then return false; end if;

    insert into public.student_gamification_balances (student_id, total_xp, points_balance, updated_at)
    values (
        p_student_id,
        greatest(0, coalesce(p_xp_delta, 0)),
        greatest(0, coalesce(p_points_delta, 0)),
        now()
    )
    on conflict (student_id) do update set
        total_xp = greatest(0, public.student_gamification_balances.total_xp + excluded.total_xp),
        points_balance = greatest(0, public.student_gamification_balances.points_balance + excluded.points_balance),
        updated_at = now();

    return true;
end;
$$;

grant usage on schema private to service_role;
grant execute on function private.ae_gamification_grant(bigint, integer, integer, text, text, text, jsonb) to service_role;

create or replace function private.ae_gamification_track_progress_trigger()
returns trigger
language plpgsql
security invoker
set search_path = public, private, pg_temp
as $$
declare
    v_day date;
begin
    v_day := (coalesce(new.last_played_at, now()) at time zone 'Asia/Taipei')::date;

    if (tg_op = 'INSERT' and new.play_count > 0)
       or (tg_op = 'UPDATE' and new.play_count > old.play_count) then
        perform private.ae_gamification_grant(
            new.student_id,
            5,
            1,
            'listening_daily',
            concat('track:', new.track_id, ':', v_day),
            '完成今日聽力練習',
            jsonb_build_object('track_id', new.track_id, 'activity_date', v_day)
        );
    end if;

    if new.completed = true and (tg_op = 'INSERT' or old.completed is distinct from true) then
        perform private.ae_gamification_grant(
            new.student_id,
            20,
            5,
            'listening_complete',
            concat('track:', new.track_id),
            '完成音檔 7 次挑戰',
            jsonb_build_object('track_id', new.track_id)
        );
    end if;

    return new;
end;
$$;

drop trigger if exists trg_ae_gamification_track_progress on public.student_track_progress;
create trigger trg_ae_gamification_track_progress
after insert or update of play_count, completed on public.student_track_progress
for each row execute function private.ae_gamification_track_progress_trigger();

