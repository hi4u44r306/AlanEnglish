create table if not exists public.student_gamification_balances (
    student_id bigint primary key references public.students(id) on delete cascade,
    total_xp integer not null default 0 check (total_xp >= 0),
    points_balance integer not null default 0 check (points_balance >= 0),
    updated_at timestamptz not null default now()
);

create table if not exists public.student_gamification_ledger (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(id) on delete cascade,
    xp_delta integer not null default 0,
    points_delta integer not null default 0,
    source_type text not null,
    source_key text not null,
    description text,
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    constraint student_gamification_ledger_nonzero check (xp_delta <> 0 or points_delta <> 0),
    constraint student_gamification_ledger_unique_source unique (student_id, source_type, source_key)
);

create table if not exists public.rewards (
    id bigint generated by default as identity primary key,
    name text not null,
    description text,
    image_path text,
    points_cost integer not null check (points_cost > 0),
    stock_quantity integer not null default 0 check (stock_quantity >= 0),
    enabled boolean not null default true,
    per_student_limit integer check (per_student_limit is null or per_student_limit > 0),
    applicable_classes text[] not null default '{}'::text[],
    sort_order integer not null default 0,
    created_by bigint references public.students(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.reward_redemptions (
    id bigint generated by default as identity primary key,
    student_id bigint not null references public.students(id) on delete cascade,
    reward_id bigint not null references public.rewards(id) on delete restrict,
    reward_name text not null,
    points_cost integer not null check (points_cost > 0),
    status text not null default 'pending' check (status in ('pending','approved','ordered','ready','completed','cancelled')),
    admin_note text,
    requested_at timestamptz not null default now(),
    approved_at timestamptz,
    ordered_at timestamptz,
    ready_at timestamptz,
    completed_at timestamptz,
    cancelled_at timestamptz,
    updated_by bigint references public.students(id) on delete set null,
    updated_at timestamptz not null default now()
);

