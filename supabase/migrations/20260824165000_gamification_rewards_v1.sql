create or replace function public.get_gamification_leaderboard(
    p_period text default 'week',
    p_class text default null,
    p_limit integer default 50
) returns table(
    rank_position bigint,
    student_id bigint,
    student_name text,
    class_name text,
    avatar_path text,
    period_xp bigint,
    total_xp integer,
    points_balance integer
)
language sql
security invoker
set search_path = public, pg_temp
as $$
    with bounds as (
        select case
            when p_period = 'week' then (
                (now() at time zone 'Asia/Taipei')::date
                - (extract(isodow from (now() at time zone 'Asia/Taipei')::date)::integer - 1)
            )::date
            when p_period = 'month' then date_trunc('month', (now() at time zone 'Asia/Taipei')::date)::date
            when p_period = 'all' then null::date
            else (
                (now() at time zone 'Asia/Taipei')::date
                - (extract(isodow from (now() at time zone 'Asia/Taipei')::date)::integer - 1)
            )::date
        end as start_date
    ),
    period_scores as (
        select ledger.student_id, coalesce(sum(ledger.xp_delta), 0)::bigint as period_xp
        from public.student_gamification_ledger ledger
        cross join bounds
        where bounds.start_date is null
           or ledger.created_at >= (bounds.start_date::timestamp at time zone 'Asia/Taipei')
        group by ledger.student_id
    ),
    scores as (
        select
            students.id as student_id,
            coalesce(nullif(students.english_name, ''), nullif(students.name, ''), 'Student') as student_name,
            students.class as class_name,
            students.user_image as avatar_path,
            coalesce(period_scores.period_xp, 0)::bigint as period_xp,
            coalesce(balance.total_xp, 0)::integer as total_xp,
            coalesce(balance.points_balance, 0)::integer as points_balance
        from public.students students
        left join public.student_gamification_balances balance on balance.student_id = students.id
        left join period_scores on period_scores.student_id = students.id
        where students.role = 'student'
          and coalesce(students.account_status, 'active') = 'active'
          and students.archived_at is null
          and (p_class is null or students.class = p_class)
    ),
    ranked as (
        select dense_rank() over (order by period_xp desc, total_xp desc, student_id asc)::bigint as rank_position, scores.*
        from scores
    )
    select rank_position, student_id, student_name, class_name, avatar_path, period_xp, total_xp, points_balance
    from ranked
    where rank_position <= least(greatest(coalesce(p_limit, 50), 1), 100)
    order by rank_position, student_id;
$$;

revoke all on function public.get_gamification_leaderboard(text, text, integer) from public, anon, authenticated;
grant execute on function public.get_gamification_leaderboard(text, text, integer) to service_role;

create or replace function public.request_reward_redemption(
    p_student_id bigint,
    p_reward_id bigint
) returns table(redemption_id bigint, status text, points_balance integer)
language plpgsql
security invoker
set search_path = public, private, pg_temp
as $$
declare
    v_reward public.rewards%rowtype;
    v_student public.students%rowtype;
    v_balance public.student_gamification_balances%rowtype;
    v_count integer := 0;
    v_redemption_id bigint;
begin
    select * into v_student from public.students where id = p_student_id and role = 'student' for update;
    if not found then raise exception 'STUDENT_NOT_FOUND'; end if;

    select * into v_reward from public.rewards where id = p_reward_id for update;
    if not found or v_reward.enabled is not true then raise exception 'REWARD_UNAVAILABLE'; end if;
    if v_reward.stock_quantity <= 0 then raise exception 'OUT_OF_STOCK'; end if;
    if cardinality(v_reward.applicable_classes) > 0 and not (coalesce(v_student.class, '') = any(v_reward.applicable_classes)) then
        raise exception 'CLASS_NOT_ELIGIBLE';
    end if;

    if v_reward.per_student_limit is not null then
        select count(*) into v_count
        from public.reward_redemptions
        where student_id = p_student_id
          and reward_id = p_reward_id
          and status <> 'cancelled';
        if v_count >= v_reward.per_student_limit then raise exception 'REDEMPTION_LIMIT_REACHED'; end if;
    end if;

    insert into public.student_gamification_balances(student_id)
    values (p_student_id)
    on conflict (student_id) do nothing;

    select * into v_balance from public.student_gamification_balances where student_id = p_student_id for update;
    if v_balance.points_balance < v_reward.points_cost then raise exception 'INSUFFICIENT_POINTS'; end if;

    insert into public.reward_redemptions(student_id, reward_id, reward_name, points_cost)
    values (p_student_id, v_reward.id, v_reward.name, v_reward.points_cost)
    returning id into v_redemption_id;

    update public.student_gamification_balances
    set points_balance = points_balance - v_reward.points_cost,
        updated_at = now()
    where student_id = p_student_id;

    insert into public.student_gamification_ledger(student_id, xp_delta, points_delta, source_type, source_key, description, metadata)
    values (
        p_student_id,
        0,
        -v_reward.points_cost,
        'reward_redemption',
        concat('redemption:', v_redemption_id),
        concat('兌換獎品：', v_reward.name),
        jsonb_build_object('reward_id', v_reward.id, 'redemption_id', v_redemption_id)
    );

    update public.rewards
    set stock_quantity = stock_quantity - 1,
        updated_at = now()
    where id = v_reward.id;

    return query
    select v_redemption_id, 'pending'::text, (v_balance.points_balance - v_reward.points_cost)::integer;
end;
$$;

revoke all on function public.request_reward_redemption(bigint, bigint) from public, anon, authenticated;
grant execute on function public.request_reward_redemption(bigint, bigint) to service_role;

create or replace function public.update_reward_redemption_status(
    p_redemption_id bigint,
    p_status text,
    p_admin_id bigint,
    p_note text default null
) returns table(redemption_id bigint, status text, points_balance integer)
language plpgsql
security invoker
set search_path = public, private, pg_temp
as $$
declare
    v_redemption public.reward_redemptions%rowtype;
    v_allowed boolean := false;
    v_balance integer := 0;
begin
    if p_status not in ('approved','ordered','ready','completed','cancelled') then raise exception 'INVALID_STATUS'; end if;

    select * into v_redemption from public.reward_redemptions where id = p_redemption_id for update;
    if not found then raise exception 'REDEMPTION_NOT_FOUND'; end if;

    if v_redemption.status = p_status then
        select points_balance into v_balance from public.student_gamification_balances where student_id = v_redemption.student_id;
        return query select v_redemption.id, v_redemption.status, coalesce(v_balance, 0);
        return;
    end if;

    v_allowed := case v_redemption.status
        when 'pending' then p_status in ('approved','cancelled')
        when 'approved' then p_status in ('ordered','ready','cancelled')
        when 'ordered' then p_status in ('ready','cancelled')
        when 'ready' then p_status in ('completed','cancelled')
        else false
    end;
    if not v_allowed then raise exception 'INVALID_STATUS_TRANSITION'; end if;

    if p_status = 'cancelled' then
        update public.student_gamification_balances
        set points_balance = points_balance + v_redemption.points_cost,
            updated_at = now()
        where student_id = v_redemption.student_id;

        insert into public.student_gamification_ledger(student_id, xp_delta, points_delta, source_type, source_key, description, metadata)
        values (
            v_redemption.student_id,
            0,
            v_redemption.points_cost,
            'reward_refund',
            concat('redemption:', v_redemption.id),
            concat('取消兌換退回點數：', v_redemption.reward_name),
            jsonb_build_object('reward_id', v_redemption.reward_id, 'redemption_id', v_redemption.id)
        )
        on conflict (student_id, source_type, source_key) do nothing;

        update public.rewards set stock_quantity = stock_quantity + 1, updated_at = now() where id = v_redemption.reward_id;
    end if;

    update public.reward_redemptions
    set status = p_status,
        admin_note = coalesce(nullif(trim(coalesce(p_note, '')), ''), admin_note),
        approved_at = case when p_status = 'approved' and approved_at is null then now() else approved_at end,
        ordered_at = case when p_status = 'ordered' and ordered_at is null then now() else ordered_at end,
        ready_at = case when p_status = 'ready' and ready_at is null then now() else ready_at end,
        completed_at = case when p_status = 'completed' and completed_at is null then now() else completed_at end,
        cancelled_at = case when p_status = 'cancelled' and cancelled_at is null then now() else cancelled_at end,
        updated_by = p_admin_id,
        updated_at = now()
    where id = v_redemption.id;

    select points_balance into v_balance from public.student_gamification_balances where student_id = v_redemption.student_id;
    return query select v_redemption.id, p_status, coalesce(v_balance, 0);
end;
$$;

revoke all on function public.update_reward_redemption_status(bigint, text, bigint, text) from public, anon, authenticated;
