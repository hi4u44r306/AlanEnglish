-- Per-question clips for the speaking challenge: a short segment of an existing private
-- listening track (audio) or of a YouTube video (video). Server-only; students receive
-- approved clips through speaking-challenge, and clip playback never counts as a listening play.
do $$
begin
    if to_regclass('public.speaking_questions') is null
       or to_regclass('public.music_tracks') is null
       or to_regclass('public.book_video_segments') is null
       or to_regclass('public.students') is null then
        raise exception 'speaking_question_media_clips: prerequisite tables missing';
    end if;
end $$;

create table if not exists public.speaking_question_media_clips (
    id bigint generated by default as identity primary key,
    question_id bigint not null references public.speaking_questions(id) on delete cascade,
    source_type text not null,
    track_id bigint references public.music_tracks(id) on delete cascade,
    youtube_video_id text,
    video_segment_id bigint references public.book_video_segments(id) on delete set null,
    start_ms integer not null,
    end_ms integer not null,
    -- Optional pre-cut private R2 object, so a clip can later be served without exposing the whole track.
    private_object_key text,
    status text not null default 'draft',
    transcript_en text,
    generation_metadata jsonb not null default '{}'::jsonb,
    created_by bigint references public.students(id) on delete set null,
    reviewed_by bigint references public.students(id) on delete set null,
    approved_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint speaking_question_media_clips_type_check
        check (source_type in ('audio', 'video')),
    constraint speaking_question_media_clips_source_check check (
        (source_type = 'audio' and track_id is not null and youtube_video_id is null and video_segment_id is null)
        or (source_type = 'video' and track_id is null and private_object_key is null
            and youtube_video_id ~ '^[A-Za-z0-9_-]{11}$')
    ),
    constraint speaking_question_media_clips_time_check check (
        start_ms >= 0 and end_ms > start_ms
        and end_ms - start_ms between 500 and 120000
        and end_ms <= 86400000
    ),
    constraint speaking_question_media_clips_object_key_check
        check (private_object_key is null or char_length(private_object_key) between 1 and 500),
    constraint speaking_question_media_clips_status_check
        check (status in ('draft', 'approved', 'archived')),
    constraint speaking_question_media_clips_approval_check
        check (status <> 'approved' or (reviewed_by is not null and approved_at is not null)),
    constraint speaking_question_media_clips_transcript_check
        check (transcript_en is null or char_length(transcript_en) <= 2000),
    constraint speaking_question_media_clips_metadata_object
        check (jsonb_typeof(generation_metadata) = 'object')
);

-- At most one approved clip per question and source type.
create unique index if not exists speaking_question_media_clips_one_approved
    on public.speaking_question_media_clips (question_id, source_type)
    where status = 'approved';
-- Re-importing the same timings is a no-op.
create unique index if not exists speaking_question_media_clips_import_unique
    on public.speaking_question_media_clips (
        question_id, source_type, coalesce(track_id, 0), coalesce(youtube_video_id, ''), start_ms, end_ms
    );
create index if not exists speaking_question_media_clips_track_idx
    on public.speaking_question_media_clips (track_id);
create index if not exists speaking_question_media_clips_segment_idx
    on public.speaking_question_media_clips (video_segment_id);
create index if not exists speaking_question_media_clips_created_by_idx
    on public.speaking_question_media_clips (created_by);
create index if not exists speaking_question_media_clips_reviewed_by_idx
    on public.speaking_question_media_clips (reviewed_by);

alter table public.speaking_question_media_clips enable row level security;
revoke all on table public.speaking_question_media_clips from public, anon, authenticated;
grant select, insert, update, delete on table public.speaking_question_media_clips to service_role;

comment on table public.speaking_question_media_clips is
    'Server-only per-question segment of an existing private listening track or YouTube video. Students only receive approved clips via speaking-challenge; playback never counts as a listening play.';

