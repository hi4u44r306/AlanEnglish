all_pages as (
    select page,
           coalesce(reviewed.activity_note,
               case
                   when page in (9, 25, 38, 62, 68, 86, 98, 116) then '歌曲頁不建立自動字卡'
                   when page in (3,4,5,6,7,8,29,33,37,45,47,49,52,54,56,58,61,63,65,67,69,72,74,76,81,83,88,91,93,95,97,103,107,110,113,115) then '描寫或單字練習空白頁，不建立自動字卡'
                   else '圖片、空格或作答內容尚不建立自動字卡'
               end) as activity_note,
           coalesce(reviewed.pronunciation_prompts, '[]'::jsonb) as pronunciation_prompts
    from generate_series(1, 119) page
    left join reviewed_pages reviewed on reviewed.page_number = page
)
insert into public.book_page_spiral_review_content (
    book_id, page_label, page_number, source_note, pronunciation_prompts,
    status, version
)
select book.id,
       'P' || all_pages.page,
       all_pages.page,
       '2026 學生新版 P' || all_pages.page || ' 已依學生版與教師版人工核對：' || all_pages.activity_note,
       all_pages.pronunciation_prompts,
       'published',
       1
from all_pages
cross join public.books book
where book.code = 'Workbook_1'
  and book.content_scope = 'formal';

do $$
begin
    if (select count(*) from public.book_page_spiral_review_content content join public.books book on book.id = content.book_id where book.code = 'Workbook_1' and content.status = 'published') <> 119 then
        raise exception 'Workbook_1 page seed must contain exactly 119 published pages';
    end if;
    if exists (
        select 1 from public.book_page_spiral_review_content content
        join public.books book on book.id = content.book_id
        where book.code = 'Workbook_1'
          and content.pronunciation_prompts::text ~ '(_{2,}|\\[\\s*\\]|Baby Shark|Twinkle Twinkle|Baa Baa Black Sheep|Cherish)'
    ) then
        raise exception 'Workbook_1 unsafe blank or song content entered the approved prompts';
    end if;
    if not exists (
        select 1 from public.book_page_spiral_review_content content
        join public.books book on book.id = content.book_id
        where book.code = 'Workbook_1'
          and jsonb_array_length(pronunciation_prompts) >= 6
    ) then
        raise exception 'Workbook_1 seed has no usable automatic-card page';
    end if;
end;
$$;

