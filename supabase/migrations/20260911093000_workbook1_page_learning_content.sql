create table if not exists public.book_page_spiral_review_content (
    id bigint generated by default as identity primary key,
    book_id bigint not null references public.books(id) on delete cascade,
    page_label text not null,
    page_number integer not null,
    source_note text not null,
    pronunciation_prompts jsonb not null default '[]'::jsonb,
    status text not null default 'draft',
    version integer not null default 1,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint book_page_spiral_review_page_label_nonempty check (btrim(page_label) <> ''),
    constraint book_page_spiral_review_page_number_positive check (page_number > 0),
    constraint book_page_spiral_review_source_note_nonempty check (btrim(source_note) <> ''),
    constraint book_page_spiral_review_prompts_array check (jsonb_typeof(pronunciation_prompts) = 'array'),
    constraint book_page_spiral_review_status_check check (status in ('draft', 'published', 'archived')),
    constraint book_page_spiral_review_version_positive check (version > 0),
    constraint book_page_spiral_review_unique_version unique (book_id, page_number, version)
);

