        raise exception 'Workbook_1 formal book is missing';
    end if;
    if exists (
        select 1 from public.book_page_spiral_review_content content
        join public.books book on book.id = content.book_id
        where book.code = 'Workbook_1'
    ) then
        raise exception 'Workbook_1 page content already exists; review versions instead of overwriting it';
    end if;
end;
$$;

