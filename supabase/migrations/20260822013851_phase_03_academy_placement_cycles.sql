-- 9. Fail fast if the fixed class catalog is incomplete.

do $$
declare
    missing_codes text[];
begin
    select array_agg(required.code order by required.code)
    into missing_codes
    from (
        values ('E1'), ('E3'), ('E5'), ('E7')
    ) as required(code)
    where not exists (
        select 1
        from public.academy_classes classes
        where classes.code = required.code
          and classes.is_active = true
    );

    if missing_codes is not null then
        raise exception 'Phase 03A failed: missing active academy classes: %',
            array_to_string(missing_codes, ', ');
    end if;
end;
$$;

commit;

select
    (select count(*) from public.academy_placement_cycles) as placement_cycle_count,
    (select count(*) from public.academy_placement_decisions) as placement_decision_count,
    (select count(*) from public.academy_class_movement_history) as class_movement_history_count,
    (
        select count(*)
        from public.academy_classes
        where code in ('E1', 'E3', 'E5', 'E7')
          and is_active = true
    ) as active_fixed_class_count;
