test("只有 service_role 能呼叫函式；歷史表啟用 RLS 且一般角色沒有權限", async () => {
    const privilege = async role => (await one(
        "select has_function_privilege($1, 'public.change_academy_student_class(bigint,text,date,text,bigint)', 'execute') allowed", [role])).allowed;
    assert.equal(await privilege("anon"), false);
    assert.equal(await privilege("authenticated"), false);
    assert.equal(await privilege("service_role"), true);

    const table = await one("select relrowsecurity from pg_class where oid = 'public.academy_class_changes'::regclass");
    assert.equal(table.relrowsecurity, true);
    for (const role of ["anon", "authenticated"]) {
        const access = await one("select has_table_privilege($1, 'public.academy_class_changes', 'select') allowed", [role]);
        assert.equal(access.allowed, false);
    }
});
