test("入班當天就調整：直接更正班級，不產生空的舊視窗", async () => {
    const { studentId, enrollmentId } = await enroll("E1", addDays(TODAY, -3));
    const result = await change(studentId, "E3", addDays(TODAY, -3));
    assert.equal(result.enrollment_id, enrollmentId);

    assert.equal((await one("select count(*)::int n from public.academy_enrollments where student_id = $1", [studentId])).n, 1);
    assert.equal((await one("select class from public.students where id = $1", [studentId])).class, "E3");
    const history = await one("select from_enrollment_id, to_enrollment_id from public.academy_class_changes where student_id = $1", [studentId]);
    assert.equal(history.from_enrollment_id, history.to_enrollment_id);
});

test("連續調整：視窗首尾相接、同時只有一個目前班級", async () => {
    const { studentId } = await enroll("E1", addDays(TODAY, -100));
    await change(studentId, "E3", addDays(TODAY, -60));
    await change(studentId, "E1", addDays(TODAY, -20), "降回原班");

    const windows = await rows(
        `select c.code, e.status, e.enrolled_at::text starts, e.access_ends_at::text ends
         from public.academy_enrollments e join public.academy_classes c on c.id = e.class_id
         where e.student_id = $1 order by e.enrolled_at`, [studentId]);
    assert.deepEqual(windows.map(item => [item.code, item.status]), [["E1", "transferred"], ["E3", "transferred"], ["E1", "active"]]);
    assert.equal(windows[0].ends, addDays(windows[1].starts, -1));
    assert.equal(windows[1].ends, addDays(windows[2].starts, -1));
    assert.equal((await one("select count(*)::int n from public.academy_enrollments where student_id = $1 and status in ('active','paused')", [studentId])).n, 1);
    assert.equal((await one("select count(*)::int n from public.academy_class_changes where student_id = $1", [studentId])).n, 2);
});

test("轉班不會被當成離校：沒有 withdrawn／graduated／departed_at", async () => {
    const { studentId } = await enroll("E3", addDays(TODAY, -40));
    await change(studentId, "E1", addDays(TODAY, -7));
    const departed = await one(
        `select count(*)::int n from public.academy_enrollments
         where student_id = $1 and (status in ('withdrawn','graduated') or departed_at is not null)`, [studentId]);
    assert.equal(departed.n, 0);
});

test("英文班權限：舊視窗結束於生效日、新視窗同日開始，原因不再寫成「離校」", async () => {
    const effective = addDays(TODAY, -15);
    const { studentId, enrollmentId } = await enroll("E1", addDays(TODAY, -50));
    await change(studentId, "E3", effective);

    const grants = await rows(
        `select source_reference_id, status, starts_at::date::text starts, ends_at::date::text ends, revoke_reason
         from public.student_access_grants where student_id = $1 order by starts_at`, [studentId]);
    assert.equal(grants.length, 2);
    assert.equal(String(grants[0].source_reference_id), String(enrollmentId));
    assert.equal(grants[0].ends, effective);
    assert.equal(grants[0].revoke_reason, "Academy class changed.");
    assert.equal(grants[1].status, "active");
    assert.equal(grants[1].starts, effective);
});

test("排定的離校日與權限截止日移到新視窗，舊視窗不再留離校排程", async () => {
    const departure = addDays(TODAY, 30);
    const accessEnd = addDays(TODAY, 200);
    const { studentId, enrollmentId } = await enroll("E1", addDays(TODAY, -40), { scheduledDepartureAt: departure, accessEndsAt: accessEnd });
    await change(studentId, "E3", addDays(TODAY, -10));

    const old = await one("select scheduled_departure_at from public.academy_enrollments where id = $1", [enrollmentId]);
    assert.equal(old.scheduled_departure_at, null);
    const current = await one(
        "select scheduled_departure_at::text sd, access_ends_at::text ae from public.academy_enrollments where student_id = $1 and status = 'active'", [studentId]);
    assert.deepEqual({ ...current }, { sd: departure, ae: accessEnd });
});

test("錯誤情況都被擋下，且不留下半套資料", async () => {
    const { studentId } = await enroll("E3", addDays(TODAY, -30));
    const before = (await one("select count(*)::int n from public.academy_enrollments")).n;

    await failsWith("ACADEMY_CLASS_UNCHANGED", () => change(studentId, "E3", TODAY));
    await failsWith("ACADEMY_CLASS_INVALID", () => change(studentId, "E2", TODAY));
    await failsWith("ACADEMY_CLASS_INVALID", () => change(studentId, "", TODAY));
    await failsWith("ACADEMY_CHANGE_DATE_IN_FUTURE", () => change(studentId, "E1", addDays(TODAY, 1)));
    await failsWith("ACADEMY_CHANGE_DATE_BEFORE_ENROLLMENT", () => change(studentId, "E1", addDays(TODAY, -31)));
    await failsWith("ACADEMY_CHANGE_REASON_INVALID", () => change(studentId, "E1", TODAY, " "));
    await failsWith("ACADEMY_CHANGE_REASON_INVALID", () => change(studentId, "E1", TODAY, "字".repeat(301)));
    await failsWith("ACADEMY_CHANGE_INVALID_INPUT", () => change(studentId, "E1", null));

    assert.equal((await one("select count(*)::int n from public.academy_enrollments")).n, before);
    assert.equal((await one("select count(*)::int n from public.academy_class_changes where student_id = $1", [studentId])).n, 0);
    assert.equal((await one("select class from public.students where id = $1", [studentId])).class, "E3");
});

test("沒有在英文班、暫停中、生效日晚於權限截止日或離校日都不能調整", async () => {
    const outsider = await one("insert into public.students (name, role) values ('no-class', 'student') returning id");
    await failsWith("ACADEMY_ENROLLMENT_NOT_FOUND", () => change(outsider.id, "E1", TODAY));

    const paused = await enroll("E3", addDays(TODAY, -30), { status: "paused" });
    await failsWith("ACADEMY_ENROLLMENT_NOT_ACTIVE", () => change(paused.studentId, "E1", TODAY));

    const ending = await enroll("E3", addDays(TODAY, -30), { accessEndsAt: addDays(TODAY, -5) });
    await failsWith("ACADEMY_CHANGE_DATE_AFTER_ACCESS_END", () => change(ending.studentId, "E1", TODAY));

    const leaving = await enroll("E3", addDays(TODAY, -30), { scheduledDepartureAt: addDays(TODAY, -2) });
    await failsWith("ACADEMY_CHANGE_DATE_AFTER_DEPARTURE", () => change(leaving.studentId, "E1", TODAY));
});

