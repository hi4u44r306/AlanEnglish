after(() => db.close());

const settle = async (elapsedSeconds, coveredSeconds, duration = 300) => {
    const { id } = await scalar(
        "insert into public.listening_coverage_sessions(student_id, track_id, duration_seconds, started_at) values (1, 1, $1, now() - make_interval(secs => $2)) returning id",
        [duration, elapsedSeconds]
    );
    try {
        await db.query("select public.complete_listening_reward_session_v3(1, 1, $1, $2::jsonb, $3, $4)",
            [id, JSON.stringify([[0, coveredSeconds]]), coveredSeconds, Number((coveredSeconds / duration * 100).toFixed(2))]);
        return "settled";
    } catch (error) {
        return String(error.message).includes("GUARD_PASSED") ? "accepted" : String(error.message);
    }
};

test("patch keeps the deployed 30-listen logic and replaces only the elapsed guard", async () => {
    const { def } = await scalar("select pg_get_functiondef('public.complete_listening_reward_session_v3(bigint,bigint,uuid,jsonb,numeric,numeric)'::regprocedure) def");
    assert.match(def, /least\(30, m\.valid_listen_count \+ 1\)/);
    assert.match(def, /greatest\(p_covered_seconds \* 0\.75, p_covered_seconds \* 0\.9 - 6\)/);
    assert.doesNotMatch(def, /< p_covered_seconds \* 0\.75 then/);
});

test("genuine listening is accepted, including a short start delay", async () => {
    assert.equal(await settle(300, 300), "accepted");            // full track, no pauses
    assert.equal(await settle(296, 300), "accepted");            // 4 s session-start delay
    assert.equal(await settle(60, 60, 60), "accepted");          // 60 s track
    assert.equal(await settle(56, 60, 60), "accepted");          // 60 s track, 4 s start delay
    assert.equal(await settle(400, 240), "accepted");            // 80 % heard with long pauses
});

test("coverage claimed far faster than real time is refused", async () => {
    assert.equal(await settle(230, 300), "INVALID_LISTENING_COVERAGE"); // old 0.75 floor allowed this
    assert.equal(await settle(100, 240), "INVALID_LISTENING_COVERAGE");
    assert.equal(await settle(10, 60, 60), "INVALID_LISTENING_COVERAGE");
});

test("archived accounts lose access; active students and staff are unchanged", async () => {
    const access = async id => (await scalar("select public.get_student_effective_access($1) a", [id])).a;
    const active = await access(1);
    assert.equal(active.is_active, true);
    assert.equal(active.features.listening, true);
    assert.deepEqual(active.plan_codes, ["academy_all_access"]);
    const archived = await access(2);
    assert.equal(archived.is_active, false);
    assert.equal(archived.features.listening, false);
    assert.deepEqual(archived.grants, []);
    assert.deepEqual(archived.plan_codes, []);
    const teacher = await access(3);
    assert.equal(teacher.is_active, true);
    assert.deepEqual(teacher.plan_codes, ["staff_unlimited"]);
    assert.equal((await access(4)).is_active, false);
    assert.equal((await access(5)).is_active, false, "no grants stays inactive");
    const grants = await scalar("select count(*)::int n from public.student_access_grants where student_id = 2 and status = 'active'");
    assert.equal(grants.n, 1, "grants are not modified, so restoring the account restores access");
    for (const role of ["anon", "authenticated"]) {
        assert.equal((await scalar("select has_function_privilege($1, 'public.get_student_effective_access(bigint, timestamp with time zone)', 'execute') ok", [role])).ok, false);
    }
    assert.equal((await scalar("select has_function_privilege('service_role', 'public.get_student_effective_access(bigint, timestamp with time zone)', 'execute') ok")).ok, true);
});
